"""Writes shared/.../content/ReviewedTexts.kt from docs/content/texts.json.

Only records the reviewer approved are written: text, source, grade, graded_by, reviewed_by and
reviewed_at all filled (CLAUDE.md rule 6). Anything else never reaches the app.
Run: python3 tools/content_to_kotlin.py          (write)
     python3 tools/content_to_kotlin.py --check  (CI: fail if the Kotlin file is stale)
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'docs/content/texts.json')
OUT = os.path.join(ROOT, 'shared/src/commonMain/kotlin/com/dcc/yawm/shared/content/ReviewedTexts.kt')
REQUIRED = ('text', 'source', 'grade', 'graded_by', 'reviewed_by', 'reviewed_at')

def kt(s):
    if s is None:
        return 'null'
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$').replace('\n', '\\n') + '"'

records = json.load(open(SRC, encoding='utf-8'))['texts']
ok = [r for r in records if all((r.get(k) or '').strip() for k in REQUIRED)]

lines = [
    '// Generated by tools/content_to_kotlin.py from docs/content/texts.json. Do not edit by hand.',
    f'// {len(ok)} of {len(records)} texts are reviewed; only those are here (CLAUDE.md rule 6).',
    'package com.dcc.yawm.shared.content',
    '',
    'internal val ReviewedTextList: List<ReligiousText> = listOf(',
]
for r in ok:
    lines.append('    ReligiousText(')
    for k, name in (('id', 'id'), ('kind', 'kind'), ('text', 'text'), ('source', 'source'), ('grade', 'grade'),
                    ('graded_by', 'gradedBy'), ('note', 'note'), ('usage', 'usage'),
                    ('reviewed_by', 'reviewedBy'), ('reviewed_at', 'reviewedAt')):
        lines.append(f'        {name} = {kt(r.get(k))},')
    lines.append('    ),')
lines.append(')')
content = '\n'.join(lines) + '\n'

if '--check' in sys.argv:
    current = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
    if current != content:
        sys.exit('ReviewedTexts.kt is out of date: run python3 tools/content_to_kotlin.py')
    print('ReviewedTexts.kt is up to date:', len(ok), 'reviewed of', len(records))
else:
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', encoding='utf-8').write(content)
    print(len(ok), 'reviewed of', len(records), '->', os.path.relpath(OUT, ROOT))
