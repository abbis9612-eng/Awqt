"""Turns docs/design/icons/color/*.svg into shared/.../ui/YawmIconData.kt.

Each icon becomes a list of parts on the 24-unit grid: outline parts are stroked in ink,
and the single filled part is painted with the icon's meaning color (docs/design/IDENTITY.md).
Run: python3 tools/icons_to_kotlin.py
"""
import glob, os, re, xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'docs/design/icons/color')
OUT = os.path.join(ROOT, 'shared/src/commonMain/kotlin/com/dcc/yawm/shared/ui/YawmIconData.kt')
NS = '{http://www.w3.org/2000/svg}'

def num(v):
    return float(v) if v else 0.0

def f(x):
    s = ('%.3f' % x).rstrip('0').rstrip('.')
    return '0' if s == '-0' else s

def circle(e):
    cx, cy, r = num(e.get('cx')), num(e.get('cy')), num(e.get('r'))
    return f'M{f(cx - r)} {f(cy)}a{f(r)} {f(r)} 0 1 0 {f(2 * r)} 0a{f(r)} {f(r)} 0 1 0 {f(-2 * r)} 0z'

def rect(e):
    x, y, w, h = (num(e.get(k)) for k in ('x', 'y', 'width', 'height'))
    rx = min(num(e.get('rx') or e.get('ry')), w / 2, h / 2)
    if rx == 0:
        return f'M{f(x)} {f(y)}h{f(w)}v{f(h)}h{f(-w)}z'
    return (f'M{f(x + rx)} {f(y)}h{f(w - 2 * rx)}a{f(rx)} {f(rx)} 0 0 1 {f(rx)} {f(rx)}v{f(h - 2 * rx)}'
            f'a{f(rx)} {f(rx)} 0 0 1 {f(-rx)} {f(rx)}h{f(-(w - 2 * rx))}a{f(rx)} {f(rx)} 0 0 1 {f(-rx)} {f(-rx)}'
            f'v{f(-(h - 2 * rx))}a{f(rx)} {f(rx)} 0 0 1 {f(rx)} {f(-rx)}z')

icons = []
for path in sorted(glob.glob(os.path.join(SRC, '*.svg'))):
    name = os.path.basename(path)[:-4]
    root = ET.parse(path).getroot()
    accent = re.search(r'--ic:(#[0-9A-Fa-f]{6})', root.get('style', '')).group(1)
    base_w = num(root.get('stroke-width'))
    parts = []
    for e in root:
        tag = e.tag.replace(NS, '')
        d = {'path': lambda e: e.get('d'), 'circle': circle, 'rect': rect}[tag](e)
        style = e.get('style') or ''
        filled = 'fill:' in style
        # The colored part may be drawn as several shapes, always in the icon's one color.
        assert not filled or accent.lower() in style.lower(), name
        width = num(e.get('stroke-width')) or base_w
        parts.append((d, filled, width))
    icons.append((name, accent, parts))

with open(OUT, 'w') as o:
    o.write('// Generated by tools/icons_to_kotlin.py from docs/design/icons/color. Do not edit by hand.\n')
    o.write('package com.dcc.yawm.shared.ui\n\n')
    o.write('internal class IconPart(val d: String, val filled: Boolean, val strokeWidth: Float)\n\n')
    o.write('internal class IconData(val accent: Long, val parts: List<IconPart>)\n\n')
    o.write('internal val YawmIconData: Map<String, IconData> = mapOf(\n')
    for name, accent, parts in icons:
        o.write(f'    "{name}" to IconData(0xFF{accent[1:].upper()}, listOf(\n')
        for d, filled, w in parts:
            o.write(f'        IconPart("{d}", {str(filled).lower()}, {f(w)}f),\n')
        o.write('    )),\n')
    o.write(')\n')
print(len(icons), 'icons ->', os.path.relpath(OUT, ROOT))
